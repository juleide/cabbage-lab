import { test, expect, _electron as electron, type Page } from '@playwright/test'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

async function unlock(page: Page) {
  await page.getByLabel('用户名', { exact: true }).fill('test-engineer')
  await page.getByLabel('密码', { exact: true }).fill('hardware-tests-only')
  await page.getByRole('button', { name: '进入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '设备连接', exact: true })).toBeVisible()
}

test('serial scan presents ports, preserves drafts and distinguishes empty and failed scans', async () => {
  const data = await mkdtemp(join(tmpdir(), 'lab-ports-'))
  const app = await electron.launch({ args: ['.', `--user-data-dir=${join(data, 'ui')}`], env: { ...process.env, LAB_DATA_DIR: data, LAB_DEVICE_DEBUG_USERNAME: 'test-engineer', LAB_DEVICE_DEBUG_PASSWORD: 'hardware-tests-only' } })
  try {
    const page = await app.firstWindow()
    await expect(page.getByText('设备已就绪', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '设备连接', exact: true }).click()
    await unlock(page)
    await page.getByRole('button', { name: '执行机构', exact: true }).click()
    await page.getByLabel('共用串口', { exact: true }).fill('COM99')
    await app.evaluate(({ ipcMain }) => {
      let count = 0
      ipcMain.removeHandler('controller:request')
      ipcMain.handle('controller:request', (_event, method) => {
        if (method !== 'hardware.ports.list') throw new Error('Unexpected test request')
        count++
        if (count === 3) throw new Error('串口扫描不可用：缺少依赖')
        return { ports: count === 2 ? [] : [{ port: 'COM7', description: 'Test adapter', manufacturer: null, vid: 123, pid: 456, serialNumber: null, location: null }] }
      })
    })
    await page.getByRole('button', { name: '扫描', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: '发现 1 个串口' })).toBeVisible()
    await expect(page.getByLabel('共用串口', { exact: true })).toHaveValue('COM99')
    await expect(page.getByText('所填端口不在本次扫描结果中', { exact: false })).toBeVisible()
    await page.getByLabel('RS485 · Modbus RTU扫描结果').selectOption('COM7')
    await expect(page.getByLabel('共用串口', { exact: true })).toHaveValue('COM7')
    await page.getByRole('button', { name: '扫描', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: '发现 0 个串口' })).toBeVisible()
    await expect(page.getByLabel('共用串口', { exact: true })).toHaveValue('COM7')
    await page.getByRole('button', { name: '扫描', exact: true }).click()
    await expect(page.getByRole('alert').filter({ hasText: '缺少依赖' })).toBeVisible()
    await expect(page.getByLabel('共用串口', { exact: true })).toHaveValue('COM7')
  } finally {
    await app.evaluate(({ BrowserWindow }) => { for (const window of BrowserWindow.getAllWindows()) window.destroy() }).catch(() => {})
    await app.close()
    await rm(data, { recursive: true, force: true })
  }
})

test('hardware draft persistence, bindings, module selection and unsaved navigation', async () => {
  const data = await mkdtemp(join(tmpdir(), 'lab-hardware-'))
  const app = await electron.launch({ args: ['.', `--user-data-dir=${join(data, 'ui')}`], env: { ...process.env, LAB_DATA_DIR: data, LAB_DEVICE_DEBUG_USERNAME: 'test-engineer', LAB_DEVICE_DEBUG_PASSWORD: 'hardware-tests-only' } })
  try {
    const page = await app.firstWindow()
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await expect(page.getByText('设备已就绪', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '设备连接', exact: true }).click()
    await unlock(page)
    await expect(page.getByRole('heading', { name: '设备连接', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '执行机构', exact: true }).click()
    await expect(page.getByLabel('1 号电机站号')).toBeVisible()
    await expect(page.getByLabel('2 号电机站号')).toBeVisible()
    await expect(page.getByRole('button', { name: /添加|移除/ })).toHaveCount(0)
    await page.getByRole('button', { name: '电子皮肤', exact: true }).click()
    const rev = page.getByLabel('REV 号')
    await rev.nth(1).selectOption('0')
    await page.getByRole('button', { name: '检查电子皮肤配置', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: '不能重复' })).toBeVisible()
    await rev.nth(0).selectOption('2')
    await page.evaluate(() => { (window as any).__originalConfirm = window.confirm; window.confirm = () => false })
    await page.getByRole('button', { name: '外观与主题', exact: true }).click()
    await expect(page.getByRole('heading', { name: '设备连接', exact: true })).toBeVisible()
    await page.evaluate(() => { window.confirm = (window as any).__originalConfirm })
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await expect(page.getByText('草稿已保存', { exact: true })).toBeVisible()
    await expect.poll(async () => JSON.parse(await readFile(join(data, 'config', 'hardware.json'), 'utf8')).array.press.rev).toBe(2)
    await page.getByRole('button', { name: '检查电子皮肤配置', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: '配置检查通过' })).toBeVisible()
    await page.getByRole('button', { name: '连接验证', exact: true }).click()
    await expect(page.getByText(/当前版本未接入真实串口及 USB 驱动/).first()).toBeVisible()
    await page.getByLabel('连接方式').selectOption('serial')
    await page.getByLabel('串口', { exact: true }).nth(0).fill('COM3')
    await page.getByLabel('串口', { exact: true }).nth(1).fill('com3')
    await page.getByLabel('波特率', { exact: true }).nth(0).fill('115200')
    await page.getByLabel('波特率', { exact: true }).nth(1).fill('115200')
    await page.getByRole('button', { name: '检查电子皮肤配置', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: '已用于' })).toBeVisible()
    await page.getByLabel('串口', { exact: true }).nth(1).fill('COM4')
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await expect(page.getByText('草稿已保存', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '拉力与位移', exact: true }).click()
    await page.getByRole('button', { name: '位移采集', exact: true }).click()
    await expect(page.getByLabel('模块类型')).toHaveValue('')
    await page.getByLabel('模块类型').selectOption('p')
    await expect(page.getByLabel('通道', { exact: true })).toBeDisabled()
    await expect(page.getByLabel('原始值上限', { exact: true })).toHaveValue('5000')
    await page.getByLabel('模块类型').selectOption('g')
    await page.getByLabel('通道', { exact: true }).selectOption('3')
    await page.getByLabel('读取方式').selectOption('float')
    await expect(page.getByLabel('位移上限', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await expect(page.getByText('草稿已保存', { exact: true })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '设备连接', exact: true }).click()
    await unlock(page)
    await page.getByRole('button', { name: '电子皮肤', exact: true }).click()
    await expect(page.getByLabel('连接方式')).toHaveValue('serial')
    await expect(page.getByLabel('串口', { exact: true }).nth(1)).toHaveValue('COM4')
    await page.screenshot({ path: '/tmp/cabbage-hardware-settings.png', fullPage: true })
    expect(errors).toEqual([])
  } finally {
    await app.evaluate(({ BrowserWindow }) => { for (const window of BrowserWindow.getAllWindows()) window.destroy() }).catch(() => {})
    await app.close().catch(() => {})
    await rm(data, { recursive: true, force: true })
  }
})

